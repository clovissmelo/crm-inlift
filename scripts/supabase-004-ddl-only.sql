-- Etapas comerciais
CREATE TABLE IF NOT EXISTS pipeline_stages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  color TEXT NOT NULL DEFAULT '#525252',
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  kind TEXT NOT NULL DEFAULT 'in_progress' CHECK (kind IN ('in_progress', 'won', 'lost')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO pipeline_stages (name, sort_order, color, status, kind)
SELECT v.name, v.sort_order, v.color, 'active', v.kind
FROM (VALUES
  ('Agendado', 10, '#6366f1', 'in_progress'),
  ('Interessado', 20, '#0ea5e9', 'in_progress'),
  ('Proposta enviada', 30, '#f59e0b', 'in_progress'),
  ('Formalizando', 40, '#a855f7', 'in_progress'),
  ('Convertido', 50, '#22c55e', 'won'),
  ('Perdido', 60, '#ef4444', 'lost')
) AS v(name, sort_order, color, kind)
WHERE NOT EXISTS (SELECT 1 FROM pipeline_stages LIMIT 1);

-- Motivos de perda (cadastro editável)
CREATE TABLE IF NOT EXISTS opportunity_loss_reasons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

INSERT INTO opportunity_loss_reasons (name, status)
SELECT v.name, 'active'
FROM (VALUES
  ('Preço'),
  ('Concorrente'),
  ('Sem budget'),
  ('Timing / adiou'),
  ('Sem resposta'),
  ('Outro')
) AS v(name)
WHERE NOT EXISTS (SELECT 1 FROM opportunity_loss_reasons LIMIT 1);

