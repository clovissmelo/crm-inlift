-- Histórico de etapas
CREATE TABLE IF NOT EXISTS opportunity_stage_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id INTEGER NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
  from_stage_id INTEGER REFERENCES pipeline_stages(id) ON DELETE SET NULL,
  to_stage_id INTEGER NOT NULL REFERENCES pipeline_stages(id) ON DELETE RESTRICT,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  notes TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_opportunity_stage_logs_opp ON opportunity_stage_logs (opportunity_id, created_at DESC);

-- Propostas
CREATE TABLE IF NOT EXISTS opportunity_proposals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id INTEGER NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
  version_number INTEGER NOT NULL,
  original_filename TEXT NOT NULL,
  storage_path TEXT NOT NULL,
  mime_type TEXT,
  file_size_bytes INTEGER NOT NULL,
  proposed_value NUMERIC(14, 2),
  valid_until DATE,
  notes TEXT,
  status TEXT NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'sent', 'accepted', 'rejected', 'superseded')),
  sent_at TIMESTAMPTZ,
  sent_channel TEXT,
  uploaded_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (opportunity_id, version_number)
);

CREATE INDEX IF NOT EXISTS idx_opportunity_proposals_opp ON opportunity_proposals (opportunity_id, version_number DESC);

-- Fotografia de conversão + correções
CREATE TABLE IF NOT EXISTS opportunity_conversion_snapshots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  opportunity_id INTEGER NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
  closer_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE RESTRICT,
  closed_at TIMESTAMPTZ NOT NULL,
  deal_value NUMERIC(14, 2),
  deal_value_tbd BOOLEAN NOT NULL DEFAULT false,
  recorded_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  recorded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  is_current BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS opportunity_conversion_amendments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id INTEGER NOT NULL REFERENCES opportunity_conversion_snapshots(id) ON DELETE CASCADE,
  opportunity_id INTEGER NOT NULL REFERENCES opportunities(id) ON DELETE CASCADE,
  previous_closer_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  previous_closed_at TIMESTAMPTZ,
  previous_deal_value NUMERIC(14, 2),
  previous_deal_value_tbd BOOLEAN,
  new_closer_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  new_closed_at TIMESTAMPTZ,
  new_deal_value NUMERIC(14, 2),
  new_deal_value_tbd BOOLEAN,
  reason TEXT NOT NULL,
  amended_by_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
