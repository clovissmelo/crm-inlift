-- Qualificação automática por resultado comercial + sessão de discagem multi-contato

ALTER TABLE approach_result_types
  ADD COLUMN IF NOT EXISTS lead_qualification TEXT
  CHECK (lead_qualification IS NULL OR lead_qualification IN ('cold', 'warm', 'hot'));

UPDATE approach_result_types SET lead_qualification = 'cold'
  WHERE slug IN ('nao_atendeu', 'chamou_sem_resposta', 'numero_invalido', 'sem_interesse')
    AND lead_qualification IS NULL;

UPDATE approach_result_types SET lead_qualification = 'warm'
  WHERE slug IN ('falou_outra_pessoa', 'pediu_retorno', 'falou_responsavel')
    AND lead_qualification IS NULL;

UPDATE approach_result_types SET lead_qualification = 'hot'
  WHERE slug IN ('demonstrou_interesse', 'reuniao_agendada')
    AND lead_qualification IS NULL;

ALTER TABLE api4com_calls
  ADD COLUMN IF NOT EXISTS dial_session_root_id INTEGER REFERENCES api4com_calls(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS api4com_dial_skips (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dial_session_root_id INTEGER NOT NULL REFERENCES api4com_calls(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  client_id INTEGER NOT NULL REFERENCES clients(id) ON DELETE CASCADE,
  contact_id INTEGER REFERENCES contacts(id) ON DELETE SET NULL,
  phone TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_api4com_dial_skips_session ON api4com_dial_skips (dial_session_root_id);
